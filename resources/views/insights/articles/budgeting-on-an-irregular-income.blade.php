<p>
    Most budgeting advice assumes the same amount lands on the same day every month. For a
    market trader, a cross-border trader, a farmer or anyone paid by the job, that is simply not
    how money arrives. A good month is followed by a thin one, and a plan built on the good month
    falls apart in the thin one.
</p>

<p>
    The answer is not to give up on a budget. It is to build one around the months you can count
    on, rather than the months you hope for.
</p>

<h2>1. Find your floor</h2>

<p>
    Look back over the last six to twelve months and write down what came in each month. Ignore
    the best months. Your <strong>floor</strong> is roughly what you earned in your weakest
    ordinary month. Not a disaster month, just a quiet one. That is the number your
    essential spending has to fit inside.
</p>

<h2>2. Split spending into must-pay and can-wait</h2>

<ul>
    <li><strong>Must-pay:</strong> rent, school fees, food, transport to work, stock you need to keep trading, and any loan repayments.</li>
    <li><strong>Can-wait:</strong> everything that could be delayed a month without real harm.</li>
</ul>

<p>
    If your must-pay list is bigger than your floor, that is worth knowing now, before a thin
    month forces the decision for you.
</p>

<h2>3. Treat good months as the buffer, not the bonus</h2>

<p>
    When a month comes in above your floor, move the difference aside before you spend it. Even a
    small buffer turns a quiet month from a crisis into an inconvenience. Once the buffer covers a
    month or two of must-pay costs, the extra can go to can-wait items or to growing the business.
</p>

<h2>4. Write it down</h2>

<p>
    A notebook works as well as an app. What matters is seeing, at the end of each week, what came
    in and what went out. Patterns you cannot see in your head, like the expense that quietly
    doubles or the customer who always pays late, are obvious on paper.
</p>

<h2>5. Borrow against your floor, not your best month</h2>

<p>
    If you take a loan, the repayment has to be affordable in a quiet month too. A repayment that
    only works when trade is good is a repayment you will eventually miss. When you talk to a
    lender, ask whether the schedule can follow how you actually earn.
</p>

