<p>
    Farming turns the usual money problem upside down. The big costs (seed, fertiliser,
    chemicals, labour) come at the start of the season, and the income only arrives months
    later at harvest. Borrowing can bridge that gap, but only if the plan follows the season
    rather than the calendar.
</p>

<h2>1. Cost the whole season, not just the inputs</h2>

<p>
    Start with the obvious costs, then add the ones that are easy to forget: transport to market,
    storage, extra labour at harvest, and the household costs you still carry while the crop is in
    the ground. A season plan that only covers seed and fertiliser tends to run short in the
    middle.
</p>

<h2>2. Be honest about the harvest</h2>

<p>
    Estimate your yield and your selling price from what you have actually achieved before, not
    from your best year. Then ask what happens if the rains are late or the price drops. If the
    plan only works in a good season, it needs a margin.
</p>

<h2>3. Match repayments to when you get paid</h2>

<p>
    The most common trap in agricultural borrowing is a repayment schedule that starts before the
    crop is sold. When you talk to a lender, explain when your income arrives and ask whether the
    schedule can follow it. A repayment you can make comfortably after harvest is far better than
    one that forces you to sell early at a poor price.
</p>

<h2>4. Keep records through the season</h2>

<p>
    Write down what you spend, what you plant and what you sell. Good records make your next
    season easier to plan and your next application easier to assess, because they show a lender
    how your farm actually earns.
</p>

<h2>5. Keep something back</h2>

<p>
    When the harvest comes in, set aside part of it for the next planting before anything else.
    Every season you can fund partly from your own savings is a season where you need to borrow
    less.
</p>

