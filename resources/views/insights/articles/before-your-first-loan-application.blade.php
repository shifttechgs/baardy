<p>
    The application that gets an answer fastest is the complete one. Most delays come from
    something missing: a document, a figure, a question nobody asked. A little preparation
    before you visit a branch saves a second trip.
</p>

<h2>1. Gather your documents</h2>

<p>
    For a salary-based loan, bring a <strong>valid national ID</strong> and your
    <strong>latest payslip</strong>. For an SME loan, also bring your
    <strong>company documents and financials</strong>. Keep them together in one folder so
    nothing is left on the kitchen table.
</p>

<h2>2. Know exactly what the money is for</h2>

<p>
    &ldquo;Stock for the December rush&rdquo; or &ldquo;Term two school fees&rdquo; is a better
    starting point than a round number. A clear purpose helps you borrow the right amount:
    not so little that you come back in a month, not so much that you pay interest on money you
    did not need.
</p>

<h2>3. Work out what you can repay</h2>

<p>
    Look at what is left over each month after your essential costs. A repayment should fit
    comfortably inside that figure, including in a quieter month. If it only fits when everything
    goes right, it is too big.
</p>

<h2>4. Ask for the total cost, not just the instalment</h2>

<p>
    A low monthly instalment can hide a long term and a large total. Before you accept any loan,
    from any lender, ask for three figures in writing:
</p>

<ul>
    <li>the interest,</li>
    <li>every fee, and</li>
    <li>the total amount you will repay.</li>
</ul>

<p>
    Then ask what happens if you want to settle early, and what happens if you miss a payment.
</p>

<h2>5. Check the lender is licensed</h2>

<p>
    In Zimbabwe, microfinance institutions are licensed by the Reserve Bank of Zimbabwe, which
    publishes its register of licensed lenders. A lender that cannot point you to its licence is a
    lender to walk away from.
</p>

